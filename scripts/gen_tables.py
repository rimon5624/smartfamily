#!/usr/bin/env python3
"""Generates the boilerplate for the tables in scripts/tables.py:

  app/.../data/db/GeneratedTables.kt   Room entities (also kotlinx-serializable) + base DAO interfaces
  app/.../sync/GeneratedSync.kt        sync registrations and backup payload for these tables
  supabase/migrations/NNNN_*.sql       one SQL file per app version, with row-level security

Run from the repository root:  python3 scripts/gen_tables.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from tables import TABLES, SHARE  # noqa: E402

PKG = "com.rimon.smartfamily"
DB_DIR = "app/src/main/java/com/rimon/smartfamily/data/db"
SYNC_DIR = "app/src/main/java/com/rimon/smartfamily/sync"


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def sql_type(kt):
    base = kt.rstrip("?")
    return {"String": "text", "Long": "bigint", "Int": "int", "Double": "double precision", "Boolean": "boolean"}[base]


def sql_default(kt, default):
    if default is None or default == "null":
        return ""
    v = default
    if kt.startswith("String"):
        return " default '" + v.strip('"').replace("'", "''") + "'"
    if kt.startswith("Long"):
        v = v.rstrip("L")
    return " default " + v


def common_fields():
    return [("id", "String", None), ("familyId", "String", None)]


def tail_fields():
    return [("updatedAt", "Long", "System.currentTimeMillis()"), ("deletedAt", "Long?", "null")]


def dao_name(t):
    return t["entity"].replace("Entity", "Dao")


def entity_kt(t):
    lines = []
    idx = ", ".join(['Index("familyId")'] + [f'Index("{i}")' for i in t.get("indices", [])])
    lines.append("@Serializable")
    lines.append(f'@Entity(tableName = "{t["name"]}", indices = [{idx}])')
    lines.append(f"data class {t['entity']}(")
    fields = common_fields() + t["fields"] + tail_fields()
    for n, kt, d in fields:
        ann = "@PrimaryKey " if n == "id" else ""
        sn = snake(n)
        ser = f'@SerialName("{sn}") ' if sn != n else ""
        default = f" = {d}" if d is not None else ""
        lines.append(f"    {ann}{ser}val {n}: {kt}{default},")
    lines.append("    @Transient val dirty: Boolean = true,")
    lines.append(")")
    return "\n".join(lines)


def base_dao_kt(t):
    e, tn, d = t["entity"], t["name"], dao_name(t)
    return f"""interface {d}Base {{
    @Query("SELECT * FROM {tn} WHERE familyId = :familyId AND deletedAt IS NULL")
    fun observeForFamily(familyId: String): Flow<List<{e}>>
    @Query("SELECT * FROM {tn} WHERE id = :id") suspend fun get(id: String): {e}?
    @Query("SELECT * FROM {tn} WHERE id = :id") fun observeOne(id: String): Flow<{e}?>
    @Upsert suspend fun upsert(item: {e})
    @Upsert suspend fun upsertAll(items: List<{e}>)
    @Query("SELECT * FROM {tn}") suspend fun all(): List<{e}>
    @Query("SELECT * FROM {tn} WHERE dirty = 1") suspend fun dirty(): List<{e}>
    @Query("UPDATE {tn} SET dirty = 0 WHERE id IN (:ids)") suspend fun markClean(ids: List<String>)
    @Query("DELETE FROM {tn}") suspend fun clear()
}}"""


def accessor(t):
    e = t["entity"].replace("Entity", "")
    return e[0].lower() + e[1:] + "s"


def write_kotlin():
    entities = "\n\n".join(entity_kt(t) for t in TABLES)
    daos = "\n\n".join(base_dao_kt(t) for t in TABLES)
    out = f"""// GENERATED by scripts/gen_tables.py from scripts/tables.py - do not edit by hand.
package {PKG}.data.db

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import androidx.room.Query
import androidx.room.Upsert
import kotlinx.coroutines.flow.Flow
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.Transient

{entities}

// Base DAOs: the feature DAOs in FeatureDaos.kt extend these and add their own queries.

{daos}
"""
    open(f"{DB_DIR}/GeneratedTables.kt", "w").write(out)

    regs = []
    for t in TABLES:
        e, acc = t["entity"], accessor(t)
        regs.append(f"""        TableSync(
            "{t['name']}", "id", {e}.serializer(),
            {{ db.{acc}().dirty() }}, {{ it.id }}, {{ db.{acc}().markClean(it) }},
            {{ rows -> db.{acc}().upsertAll(rows.map {{ it.copy(dirty = false) }}) }}, {{ it.updatedAt }},
        ),""")
    payload_fields = "\n".join(f"    val {accessor(t)}: List<{t['entity']}> = emptyList()," for t in TABLES)
    export_lines = "\n".join(f"        {accessor(t)} = db.{accessor(t)}().all()," for t in TABLES)
    clear_lines = "\n".join(f"    db.{accessor(t)}().clear()" for t in TABLES)
    restore_lines = "\n".join(
        f"    db.{accessor(t)}().upsertAll(p.{accessor(t)}.map {{ it.copy(dirty = true) }})" for t in TABLES
    )
    imports = "\n".join(f"import {PKG}.data.db.{t['entity']}" for t in TABLES)
    sync = f"""// GENERATED by scripts/gen_tables.py from scripts/tables.py - do not edit by hand.
package {PKG}.sync

import {PKG}.data.db.AppDatabase
{imports}
import kotlinx.serialization.Serializable

internal fun generatedTableSyncs(db: AppDatabase): List<TableSync<*>> = listOf(
{chr(10).join(regs)}
)

/** Backup content of the generated tables (BAK-2); missing lists in older backups default to empty. */
@Serializable
data class GeneratedBackup(
{payload_fields}
)

suspend fun exportGenerated(db: AppDatabase) = GeneratedBackup(
{export_lines}
)

suspend fun clearGenerated(db: AppDatabase) {{
{clear_lines}
}}

suspend fun restoreGenerated(db: AppDatabase, p: GeneratedBackup) {{
{restore_lines}
}}
"""
    open(f"{SYNC_DIR}/GeneratedSync.kt", "w").write(sync)


POLICY_WRITE = {
    "adults": "public.sf_my_role(family_id) in ('OWNER','ADMIN','MEMBER')",
    "members": "public.sf_my_role(family_id) in ('OWNER','ADMIN','MEMBER','CHILD')",
    "admins": "public.sf_my_role(family_id) in ('OWNER','ADMIN')",
    # rows a member writes only for themselves (their key, their read marker, their reaction)
    "self": "public.sf_is_member(family_id) and user_id = auth.uid()::text",
    # chat messages: only the sender may write or edit them
    "sender": "public.sf_is_member(family_id) and sender_id = auth.uid()::text",
}


def table_sql(t):
    cols = []
    for n, kt, d in common_fields() + t["fields"] + tail_fields():
        sn = snake(n)
        if n == "id":
            cols.append("  id text primary key")
            continue
        if n == "familyId":
            cols.append("  family_id text not null references public.families(id) on delete cascade")
            continue
        if n == "updatedAt":
            cols.append("  updated_at bigint not null default public.sf_now_ms()")
            continue
        null = "" if kt.endswith("?") else " not null"
        cols.append(f"  {sn} {sql_type(kt)}{null}{sql_default(kt, d)}")
    tn = t["name"]
    w = POLICY_WRITE[t["policy"]]
    s = [f"create table if not exists public.{tn} (\n" + ",\n".join(cols) + "\n);"]
    # columns added to an existing table in a later version
    for n, kt, d in t["fields"]:
        null = "" if kt.endswith("?") else " not null"
        dflt = sql_default(kt, d) or (" default ''" if kt == "String" else " default 0" if kt in ("Int", "Long", "Double") else " default false" if kt == "Boolean" else "")
        s.append(f"alter table public.{tn} add column if not exists {snake(n)} {sql_type(kt)}{null if dflt else ''}{dflt};")
    s.append(f"create index if not exists {tn}_updated_idx on public.{tn}(updated_at);")
    s.append(f"create index if not exists {tn}_family_idx on public.{tn}(family_id);")
    s.append(f"drop trigger if exists sf_touch_{tn} on public.{tn};")
    s.append(f"create trigger sf_touch_{tn} before insert or update on public.{tn} for each row execute function public.sf_touch();")
    s.append(f"alter table public.{tn} enable row level security;")
    s.append(f"drop policy if exists {tn}_select on public.{tn};")
    s.append(f"create policy {tn}_select on public.{tn} for select to authenticated using (public.sf_is_member(family_id));")
    s.append(f"drop policy if exists {tn}_insert on public.{tn};")
    s.append(f"create policy {tn}_insert on public.{tn} for insert to authenticated with check ({w});")
    s.append(f"drop policy if exists {tn}_update on public.{tn};")
    s.append(f"create policy {tn}_update on public.{tn} for update to authenticated using ({w}) with check ({w});")
    return "\n".join(s)


def write_sql():
    versions = sorted({t["version"] for t in TABLES})
    for v in versions:
        ts = [t for t in TABLES if t["version"] == v and t.get("sql", True)]
        if not ts:
            continue
        fn = f"supabase/migrations/{v:04d}_app_0_{v}.sql"
        body = "\n\n".join(table_sql(t) for t in ts)
        open(fn, "w").write(
            f"-- SmartFamily - Supabase schema for app 0.{v}.0 (GENERATED by scripts/gen_tables.py).\n"
            f"-- Run once after the earlier numbered files: SQL Editor -> New query -> paste -> Run. Safe to run again.\n"
            f"-- Tables: {', '.join(t['name'] for t in ts)}\n\n{body}\n"
        )
    rows = []
    for t in TABLES:
        if t["name"] not in SHARE:
            continue
        mod, col = SHARE[t["name"]]
        chat = t["name"].startswith("chat")
        guard = ("id" if t["name"] == "chats" else "chat_id") if chat else ""
        w = {"self": "", "sender": ""}.get(t["policy"], POLICY_WRITE[t["policy"]])
        owner = {"self": "user_id", "sender": "sender_id"}.get(t["policy"], "")
        q = lambda x: "'" + x.replace("'", "''") + "'"
        rows.append(f"    ({q(t['name'])}, {q(mod)}, {q(col or 'null')}, {q(guard)}, {q(w)}, {q(owner)})")
    body = """do $$
declare r record; rd text; wr text; base text;
begin
  for r in select * from (values
""" + ",\n".join(rows) + """
  ) as v(tn, modx, item, guard, w, owner) loop
    rd := format('public.sf_shared(family_id, %s, %s, false)', r.modx, r.item);
    wr := format('public.sf_shared(family_id, %s, %s, true)', r.modx, r.item);
    if r.guard <> '' then
      rd := rd || format(' and public.sf_chat_member(%s)', r.guard);
      wr := wr || format(' and public.sf_chat_member(%s)', r.guard);
    end if;
    if r.owner <> '' then
      base := format('(public.sf_is_member(family_id) or %s) and %s = auth.uid()::text', wr, r.owner);
    else
      base := format('(%s) or (%s)', r.w, wr);
    end if;
    execute format('drop policy if exists %1$s_select on public.%1$s', r.tn);
    execute format('create policy %1$s_select on public.%1$s for select to authenticated using (public.sf_is_member(family_id) or (%2$s))', r.tn, rd);
    execute format('drop policy if exists %1$s_insert on public.%1$s', r.tn);
    execute format('create policy %1$s_insert on public.%1$s for insert to authenticated with check (%2$s)', r.tn, base);
    execute format('drop policy if exists %1$s_update on public.%1$s', r.tn);
    execute format('create policy %1$s_update on public.%1$s for update to authenticated using (%2$s) with check (%2$s)', r.tn, base);
  end loop;
end $$;"""
    open("supabase/migrations/0009_z_sharing_policies.sql", "w").write(
        "-- SmartFamily 0.9.0 - row-level security with sharing between families (GENERATED by scripts/gen_tables.py).\n"
        "-- Run after 0009_a_sharing.sql. Safe to run again.\n"
        "-- Each table keeps its own rule and also allows access granted by an accepted share from another family.\n\n" + body + "\n"
    )


if __name__ == "__main__":
    write_kotlin()
    write_sql()
    print("Generated", len(TABLES), "tables")
